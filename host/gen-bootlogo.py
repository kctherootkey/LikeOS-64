#!/usr/bin/env python3
# LikeOS -- turn the logo PNG into a C header for the UEFI boot menu.
#
# The boot loader has no image decoder; it draws the logo from a table of
# premultiplied-alpha pixels compiled into it.  This script makes that table
# from the 256x256 application icon:
#
#     python3 host/gen-bootlogo.py [in.png] [out.h]
#
# Defaults: res/xorg/icons/LikeOS/256x256/apps/likeos-logo.png and
# boot/bootlogo.h.  The header is committed, so building the loader needs
# no Python; rerun this after the icon changes.
#
# Only the standard library is used (zlib for the image data): non-interlaced
# PNGs with 8 bits per channel, colour types RGBA, RGB, grey and grey+alpha,
# all five scanline filters.
#
# Copyright (C) 2026 The LikeOS Project

import os
import struct
import sys
import zlib

DEFAULT_IN = "res/xorg/icons/LikeOS/256x256/apps/likeos-logo.png"
DEFAULT_OUT = "boot/bootlogo.h"

# Colour type -> channels.
CHANNELS = {0: 1, 2: 3, 4: 2, 6: 4}


def paeth(a, b, c):
    p = a + b - c
    pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
    if pa <= pb and pa <= pc:
        return a
    if pb <= pc:
        return b
    return c


def decode_png(path):
    """Return (width, height, list of (r, g, b, a) rows, straight alpha)."""
    with open(path, "rb") as f:
        data = f.read()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise SystemExit("%s: not a PNG file" % path)
    pos = 8
    ihdr = None
    idat = []
    while pos < len(data):
        (length,) = struct.unpack(">I", data[pos:pos + 4])
        ctype = data[pos + 4:pos + 8]
        body = data[pos + 8:pos + 8 + length]
        (crc,) = struct.unpack(">I", data[pos + 8 + length:pos + 12 + length])
        if zlib.crc32(ctype + body) & 0xFFFFFFFF != crc:
            raise SystemExit("%s: bad CRC in chunk %r" % (path, ctype))
        pos += 12 + length
        if ctype == b"IHDR":
            ihdr = struct.unpack(">IIBBBBB", body)
        elif ctype == b"IDAT":
            idat.append(body)
        elif ctype == b"IEND":
            break
    if ihdr is None:
        raise SystemExit("%s: no IHDR chunk" % path)
    width, height, depth, colour, comp, filt, interlace = ihdr
    if depth != 8 or colour not in CHANNELS or comp != 0 or filt != 0:
        raise SystemExit("%s: only 8-bit grey/RGB/grey+alpha/RGBA PNGs are "
                         "supported (depth %d, colour type %d)"
                         % (path, depth, colour))
    if interlace != 0:
        raise SystemExit("%s: interlaced PNGs are not supported" % path)
    nch = CHANNELS[colour]
    stride = width * nch
    raw = zlib.decompress(b"".join(idat))
    if len(raw) < height * (stride + 1):
        raise SystemExit("%s: image data too short" % path)
    prev = bytearray(stride)
    rows = []
    for y in range(height):
        base = y * (stride + 1)
        ftype = raw[base]
        line = bytearray(raw[base + 1:base + 1 + stride])
        for i in range(stride):
            a = line[i - nch] if i >= nch else 0
            b = prev[i]
            c = prev[i - nch] if i >= nch else 0
            if ftype == 0:
                pass
            elif ftype == 1:
                line[i] = (line[i] + a) & 0xFF
            elif ftype == 2:
                line[i] = (line[i] + b) & 0xFF
            elif ftype == 3:
                line[i] = (line[i] + ((a + b) >> 1)) & 0xFF
            elif ftype == 4:
                line[i] = (line[i] + paeth(a, b, c)) & 0xFF
            else:
                raise SystemExit("%s: bad filter type %d in row %d"
                                 % (path, ftype, y))
        px = []
        for x in range(width):
            p = line[x * nch:(x + 1) * nch]
            if colour == 6:
                px.append((p[0], p[1], p[2], p[3]))
            elif colour == 2:
                px.append((p[0], p[1], p[2], 255))
            elif colour == 4:
                px.append((p[0], p[0], p[0], p[1]))
            else:
                px.append((p[0], p[0], p[0], 255))
        rows.append(px)
        prev = line
    return width, height, rows


def premultiply(r, g, b, a):
    """0xAARRGGBB with the colour channels multiplied by alpha (rounded)."""
    def m(c):
        return (c * a + 127) // 255
    return (a << 24) | (m(r) << 16) | (m(g) << 8) | m(b)


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_IN
    out = sys.argv[2] if len(sys.argv) > 2 else DEFAULT_OUT
    width, height, rows = decode_png(src)
    words = [premultiply(*p) for row in rows for p in row]
    lines = []
    lines.append("/* Generated by host/gen-bootlogo.py from %s -- do not edit."
                 % src.replace(os.sep, "/"))
    lines.append(" *")
    lines.append(" * The LikeOS logo for the UEFI boot menu (boot/gfx.c).  Rerun the")
    lines.append(" * script after the icon changes.")
    lines.append(" *")
    lines.append(" * Copyright (C) 2026 The LikeOS Project")
    lines.append(" */")
    lines.append("")
    lines.append("#ifndef LIKEOS_BOOT_BOOTLOGO_H")
    lines.append("#define LIKEOS_BOOT_BOOTLOGO_H")
    lines.append("")
    lines.append("#define BOOTLOGO_W %d" % width)
    lines.append("#define BOOTLOGO_H %d" % height)
    lines.append("")
    lines.append("/* Premultiplied alpha, one 0xAARRGGBB word per pixel, row-major. */")
    lines.append("static const unsigned int bootlogo_argb[BOOTLOGO_W * BOOTLOGO_H] = {")
    for i in range(0, len(words), 8):
        chunk = words[i:i + 8]
        lines.append("\t" + ", ".join("0x%08x" % w for w in chunk) + ",")
    lines.append("};")
    lines.append("")
    lines.append("#endif /* LIKEOS_BOOT_BOOTLOGO_H */")
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("%s: %dx%d -> %s" % (src, width, height, out))


if __name__ == "__main__":
    main()

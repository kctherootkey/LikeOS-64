/* ---- Case mapping ---------------------------------------------------------- */

/* Binary search of a {key, value} pair table sorted by key. */
uint16_t fat_pair_lookup(const uint16_t (*tab)[2], unsigned n, uint16_t c)
{
	unsigned lo = 0, hi = n;

	while (lo < hi) {
		unsigned mid = lo + (hi - lo) / 2;

		if (tab[mid][0] < c)
			lo = mid + 1;
		else if (tab[mid][0] > c)
			hi = mid;
		else
			return tab[mid][1];
	}
	return c;
}

/* The upper-case form of a code unit (itself when it has none). */
static inline uint16_t fat_upc(uint16_t c)
{
	if (c < 0x80)
		return (c >= 'a' && c <= 'z') ? (uint16_t)(c - 32) : c;
	return fat_pair_lookup(fat_upcase_tab, FAT_UPCASE_PAIRS, c);
}

void fat_fold(const uint16_t *in, unsigned n, uint16_t *out)
{
	for (unsigned i = 0; i < n; i++)
		out[i] = fat_upc(in[i]);
}

/* Two names equal after folding?  `up' is folded already. */
int fat_name_eq(const uint16_t *a, unsigned na, const uint16_t *up,
		       unsigned n)
{
	if (na != n)
		return 0;
	for (unsigned i = 0; i < n; i++)
		if (fat_upc(a[i]) != up[i])
			return 0;
	return 1;
}

/* ---- OEM code pages ---------------------------------------------------------- */

const struct fat_codepage *fat_cp_find(int number)
{
	for (unsigned i = 0; i < sizeof(fat_codepages) / sizeof(fat_codepages[0]);
	     i++)
		if (fat_codepages[i].number == number)
			return &fat_codepages[i];
	return NULL;
}

/* The byte of character `u' in the code page, 0 when it has none. */
uint8_t fat_cp_from_uni(const struct fat_codepage *cp, uint16_t u)
{
	if (u == 0)
		return 0;
	if (u < 0x80)
		return (uint8_t)u;
	for (unsigned i = 0; i < 128; i++)
		if (cp->high[i] == u)
			return (uint8_t)(0x80 + i);
	return 0;
}

/* The upper-case form of a code-page byte (itself when the code page holds
 * no upper-case form of its character). */
uint8_t fat_cp_toupper(const struct fat_codepage *cp, uint8_t b)
{
	uint16_t u, U;
	uint8_t r;

	if (b < 0x80)
		return (b >= 'a' && b <= 'z') ? (uint8_t)(b - 32) : b;
	u = cp->high[b - 0x80];
	if (!u)
		return b;
	U = fat_upc(u);
	if (U == u)
		return b;
	r = fat_cp_from_uni(cp, U);
	return r ? r : b;
}

/* ---- UTF-8 <-> UTF-16 ----------------------------------------------------------- */

/* UTF-8 (`len' bytes) -> UTF-16 in `out' (room for `max' units).  Code
 * points above U+FFFF become surrogate pairs; three-byte encodings of
 * surrogates are taken as they are (see above).  Returns the number of
 * units, ST_NAMETOOLONG, or ST_INVALID for malformed UTF-8. */
static int fat_utf8_to_utf16(const char *s, unsigned long len, uint16_t *out,
			     unsigned max)
{
	const uint8_t *p = (const uint8_t *)s;
	unsigned long i = 0;
	unsigned n = 0;

	while (i < len) {
		uint32_t cp;
		unsigned extra;
		uint8_t c = p[i];

		if (c < 0x80) {
			cp = c;
			extra = 0;
		} else if ((c & 0xE0) == 0xC0) {
			cp = c & 0x1F;
			extra = 1;
		} else if ((c & 0xF0) == 0xE0) {
			cp = c & 0x0F;
			extra = 2;
		} else if ((c & 0xF8) == 0xF0) {
			cp = c & 0x07;
			extra = 3;
		} else {
			return ST_INVALID;
		}
		/* The continuation bytes must all be there. */
		if (extra && i + extra >= len)
			return ST_INVALID;
		for (unsigned k = 1; k <= extra; k++) {
			uint8_t cc = p[i + k];

			if ((cc & 0xC0) != 0x80)
				return ST_INVALID;
			cp = (cp << 6) | (cc & 0x3F);
		}
		/* Overlong forms and values past Unicode are malformed. */
		if ((extra == 1 && cp < 0x80) || (extra == 2 && cp < 0x800) ||
		    (extra == 3 && (cp < 0x10000 || cp > 0x10FFFF)))
			return ST_INVALID;
		i += 1 + extra;
		if (cp >= 0x10000) {
			if (n + 2 > max)
				return ST_NAMETOOLONG;
			cp -= 0x10000;
			out[n++] = (uint16_t)(0xD800 | (cp >> 10));
			out[n++] = (uint16_t)(0xDC00 | (cp & 0x3FF));
		} else {
			if (n + 1 > max)
				return ST_NAMETOOLONG;
			out[n++] = (uint16_t)cp;
		}
	}
	return (int)n;
}

/* UTF-16 -> UTF-8 into `out' (`cap' bytes, NUL included).  Returns the
 * length without the NUL, or -1 when it does not fit. */
int fat_utf16_to_utf8(const uint16_t *in, unsigned n, char *out,
			     unsigned cap)
{
	unsigned o = 0;

	for (unsigned i = 0; i < n; i++) {
		uint32_t cp = in[i];

		if (cp >= 0xD800 && cp <= 0xDBFF && i + 1 < n &&
		    in[i + 1] >= 0xDC00 && in[i + 1] <= 0xDFFF) {
			cp = 0x10000 + ((cp - 0xD800) << 10) +
			     (in[i + 1] - 0xDC00);
			i++;
		}
		if (cp < 0x80) {
			if (o + 1 >= cap)
				return -1;
			out[o++] = (char)cp;
		} else if (cp < 0x800) {
			if (o + 2 >= cap)
				return -1;
			out[o++] = (char)(0xC0 | (cp >> 6));
			out[o++] = (char)(0x80 | (cp & 0x3F));
		} else if (cp < 0x10000) {
			if (o + 3 >= cap)
				return -1;
			out[o++] = (char)(0xE0 | (cp >> 12));
			out[o++] = (char)(0x80 | ((cp >> 6) & 0x3F));
			out[o++] = (char)(0x80 | (cp & 0x3F));
		} else {
			if (o + 4 >= cap)
				return -1;
			out[o++] = (char)(0xF0 | (cp >> 18));
			out[o++] = (char)(0x80 | ((cp >> 12) & 0x3F));
			out[o++] = (char)(0x80 | ((cp >> 6) & 0x3F));
			out[o++] = (char)(0x80 | (cp & 0x3F));
		}
	}
	if (o >= cap)
		return -1;
	out[o] = 0;
	return (int)o;
}

static int fat_hexval(char c)
{
	if (c >= '0' && c <= '9')
		return c - '0';
	if (c >= 'a' && c <= 'f')
		return c - 'a' + 10;
	if (c >= 'A' && c <= 'F')
		return c - 'A' + 10;
	return -1;
}

/* A name at the system interface (iocharset=) -> UTF-16.  Returns the
 * number of units, ST_NAMETOOLONG or ST_INVALID. */
int fat_ext_to_utf16(fat_fs_t *fs, const char *s, unsigned long len,
			    uint16_t *out, unsigned max)
{
	unsigned n = 0;

	if (fs->opts.iocharset == FAT_IOCS_UTF8)
		return fat_utf8_to_utf16(s, len, out, max);
	for (unsigned long i = 0; i < len;) {
		uint8_t c = (uint8_t)s[i];
		uint16_t u;

		if (fs->opts.uni_xlate && c == ':' && i + 4 < len) {
			int h0 = fat_hexval(s[i + 1]), h1 = fat_hexval(s[i + 2]),
			    h2 = fat_hexval(s[i + 3]), h3 = fat_hexval(s[i + 4]);

			if (h0 >= 0 && h1 >= 0 && h2 >= 0 && h3 >= 0) {
				/* ":xxxx": the code unit in hexadecimal. */
				u = (uint16_t)((h0 << 12) | (h1 << 8) |
					       (h2 << 4) | h3);
				if (n + 1 > max)
					return ST_NAMETOOLONG;
				out[n++] = u;
				i += 5;
				continue;
			}
		}
		if (fs->opts.iocharset == FAT_IOCS_ASCII && c >= 0x80)
			return ST_INVALID;
		if (n + 1 > max)
			return ST_NAMETOOLONG;
		out[n++] = c;
		i++;
	}
	return (int)n;
}

/* UTF-16 -> a name at the system interface into `out' (`cap' bytes, NUL
 * included).  Returns the length, or -1 when it does not fit. */
int fat_utf16_to_ext(fat_fs_t *fs, const uint16_t *in, unsigned n,
			    char *out, unsigned cap)
{
	static const char hex[] = "0123456789abcdef";
	unsigned o = 0, lim;

	if (fs->opts.iocharset == FAT_IOCS_UTF8)
		return fat_utf16_to_utf8(in, n, out, cap);
	lim = fs->opts.iocharset == FAT_IOCS_ASCII ? 0x80 : 0x100;
	for (unsigned i = 0; i < n; i++) {
		uint16_t u = in[i];

		if (u < lim) {
			if (o + 1 >= cap)
				return -1;
			out[o++] = (char)u;
		} else if (fs->opts.uni_xlate) {
			if (o + 5 >= cap)
				return -1;
			out[o++] = ':';
			out[o++] = hex[(u >> 12) & 0xF];
			out[o++] = hex[(u >> 8) & 0xF];
			out[o++] = hex[(u >> 4) & 0xF];
			out[o++] = hex[u & 0xF];
		} else {
			if (o + 1 >= cap)
				return -1;
			out[o++] = '?';
		}
	}
	if (o >= cap)
		return -1;
	out[o] = 0;
	return (int)o;
}

/* ---- Long names ------------------------------------------------------------------- */

/* Characters a long name may not contain. */
int fat_lfn_bad_char(uint16_t c)
{
	if (c < 0x20)
		return 1;
	switch (c) {
	case '*':
	case '?':
	case '<':
	case '>':
	case '|':
	case '"':
	case ':':
	case '/':
	case '\\':
		return 1;
	}
	return 0;
}

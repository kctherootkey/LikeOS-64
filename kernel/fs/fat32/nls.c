/* ===========================================================================
 * 10. Names
 *
 * Every name on the volume is handled as UTF-16 inside the driver:
 *
 *  - long names: the code units of the long-name entries (up to 255);
 *  - short names: the 11 bytes of the short entry, in the OEM code page
 *    (codepage=), shown as "BASE.EXT" with the case rules of shortname=.
 *
 * At the system interface names are UTF-8 (iocharset=utf8, surrogate pairs
 * for code points above U+FFFF; an unpaired surrogate on the volume is
 * carried as its three-byte form, so every name can be listed AND opened
 * again), or ISO 8859-1 / ASCII bytes (characters outside become "?" or,
 * with uni_xlate, ":xxxx").  Lookups compare names folded through the
 * Unicode simple upper-case mapping: long names and short names alike, so
 * "readme.txt", "README.TXT" and "Readme.Txt" all name the same file.
 * =========================================================================== */


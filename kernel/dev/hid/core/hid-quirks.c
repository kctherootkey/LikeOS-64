bool hid_ignore(struct hid_device *hdev)
{
	if (hdev->quirks & HID_QUIRK_NO_IGNORE)
		return false;
	if (hdev->quirks & HID_QUIRK_IGNORE)
		return true;

	switch (hdev->vendor) {
	case USB_VENDOR_ID_CODEMERCS:
		/* Code Mercenaries IOWarrior devices */
		if (hdev->product >= USB_DEVICE_ID_CODEMERCS_IOW_FIRST &&
		    hdev->product <= USB_DEVICE_ID_CODEMERCS_IOW_LAST)
			return true;
		break;
	case USB_VENDOR_ID_LOGITECH:
		if (hdev->product >= USB_DEVICE_ID_LOGITECH_HARMONY_FIRST &&
		    hdev->product <= USB_DEVICE_ID_LOGITECH_HARMONY_LAST)
			return true;
		/* The Keene FM transmitter shares its ID with the Logitech
		 * AudioHub speaker ("HOLTEK  AudioHub Speaker"); only the
		 * transmitter is not a HID device. */
		if (hdev->product == USB_DEVICE_ID_LOGITECH_AUDIOHUB &&
		    !kstrcmp(hdev->name, "HOLTEK  B-LINK USB Audio  "))
			return true;
		break;
	case USB_VENDOR_ID_SOUNDGRAPH:
		if (hdev->product >= USB_DEVICE_ID_SOUNDGRAPH_IMON_FIRST &&
		    hdev->product <= USB_DEVICE_ID_SOUNDGRAPH_IMON_LAST)
			return true;
		break;
	case USB_VENDOR_ID_HANWANG:
		if (hdev->product >= USB_DEVICE_ID_HANWANG_TABLET_FIRST &&
		    hdev->product <= USB_DEVICE_ID_HANWANG_TABLET_LAST)
			return true;
		break;
	case USB_VENDOR_ID_VELLEMAN:
		/* Data acquisition boards, not HID devices. */
		if ((hdev->product >= USB_DEVICE_ID_VELLEMAN_K8055_FIRST &&
		     hdev->product <= USB_DEVICE_ID_VELLEMAN_K8055_LAST) ||
		    (hdev->product >= USB_DEVICE_ID_VELLEMAN_K8061_FIRST &&
		     hdev->product <= USB_DEVICE_ID_VELLEMAN_K8061_LAST))
			return true;
		break;
	case USB_VENDOR_ID_ATMEL_V_USB:
		/* The Masterkit MA901 radio shares the ID of many Atmel
		 * V-USB devices; told apart by its name. */
		if (hdev->product == USB_DEVICE_ID_ATMEL_V_USB &&
		    hdev->bus == BUS_USB &&
		    kstrncmp(hdev->name, "www.masterkit.ru MA901", 22) == 0)
			return true;
		break;
	case USB_VENDOR_ID_JIELI_SDK_DEFAULT:
		/* A microphone and a touchscreen share the ID; the
		 * microphone is told apart by maker and serial number. */
		if (hdev->product == USB_DEVICE_ID_JIELI_SDK_4155 &&
		    kstrncmp(hdev->name, "SmartlinkTechnology", 19) == 0 &&
		    kstrncmp(hdev->uniq, "20201111000001", 14) == 0)
			return true;
		break;
	}
	/* ELAN 0x0400/0x0401 touchpads are not ignored: there is no other
	 * driver for them here, and over I2C-HID they speak HID. */

	return hid_match_id(hdev, hid_ignore_list) != NULL;
}

unsigned long hid_lookup_quirk(const struct hid_device *hdev)
{
	const struct hid_device_id *entry;
	unsigned long quirks = 0;

	if (!hdev)
		return 0;

	/* NCR devices must never be asked for reports. */
	if (hdev->bus == BUS_USB && hdev->vendor == USB_VENDOR_ID_NCR &&
	    hdev->product >= USB_DEVICE_ID_NCR_FIRST &&
	    hdev->product <= USB_DEVICE_ID_NCR_LAST)
		return HID_QUIRK_NO_INIT_REPORTS;

	/* These must be ignored when their firmware is too old. */
	if (hdev->bus == BUS_USB && hdev->vendor == USB_VENDOR_ID_JABRA) {
		switch (hdev->product) {
		case USB_DEVICE_ID_JABRA_SPEAK_410:
			if (hdev->version < 0x0111)
				return HID_QUIRK_IGNORE;
			break;
		case USB_DEVICE_ID_JABRA_SPEAK_510:
			if (hdev->version < 0x0214)
				return HID_QUIRK_IGNORE;
			break;
		}
	}

	if (hid_match_id(hdev, hid_ignore_list))
		quirks |= HID_QUIRK_IGNORE;
	entry = hid_match_id(hdev, hid_quirks);
	if (entry)
		quirks |= entry->driver_data;
	/* What the transport found out about the device. */
	quirks |= hdev->initial_quirks;
	return quirks;
}

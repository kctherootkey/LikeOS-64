// LikeOS HID core - per-device quirks
//
// Some devices need the core to behave differently: not to query reports
// at setup (their firmware hangs on GET_REPORT), to make one input device
// per report, to be polled although nobody listens, or to be left alone
// entirely.  The quirks are looked up by bus, vendor and product when a
// device is added and again before every driver binding (a driver's own
// changes to hdev->quirks do not outlive its binding).
//
// The tables list every device known to need a quirk.  Entries whose
// device belongs to a driver LikeOS does not have (a dedicated driver that
// would take the device instead) are left out, so those devices still get
// the generic handling.

/* ---- PLL states ------------------------------------------------------------- */

/* One MPLLB configuration: the port clock it produces (kHz: the DP link
 * rate or the TMDS clock) and the words as they are written. */
struct mpllb_state {
	uint32_t clock;
	uint32_t ref_control;
	uint32_t mpllb_cp;
	uint32_t mpllb_div;
	uint32_t mpllb_div2;
	uint32_t mpllb_fracn1;
	uint32_t mpllb_fracn2;
	uint32_t mpllb_sscen;
	uint32_t mpllb_sscstep;
};


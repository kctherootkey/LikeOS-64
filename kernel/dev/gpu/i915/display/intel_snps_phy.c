// LikeOS -- the Synopsys port PHYs of DG2 (Arc A-series, display version 13).
//
// DG2 drives its five DDIs through Synopsys PHYs rather than the combo
// and Type-C PHYs of the integrated parts.  Each PHY carries its own PLL
// (the "MPLLB"), which takes the place of the shared display PLLs other
// generations route ports to: a port is clocked by programming its own
// PHY's PLL during the mode set and starting it from the port's PLL
// enable word.  The PLL settings are looked up in tables of register
// values validated for each DisplayPort link rate and for the common
// HDMI clocks; an HDMI clock the tables do not list gets settings
// computed from the PHY's characterisation curves.  The transmitter's
// swing and pre-emphasis are three equalisation fields per lane,
// written straight into the PHY.
//
// At display initialisation every PHY runs a calibration and adaptation
// pass, which the driver waits out before using any port; a PHY that
// does not finish is noted and driven anyway.
//
// None of this has run on hardware here; every step reports what it
// found.
//

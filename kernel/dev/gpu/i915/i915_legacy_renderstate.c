struct null_state {
	const uint32_t *reloc;
	uint32_t nreloc;
	const uint32_t *batch;
	uint32_t items;
};

static int null_state_for(int gen, struct null_state *ns)
{
	switch (gen) {
	case 6:
		ns->reloc = gen6_null_state_relocs;
		ns->nreloc = sizeof(gen6_null_state_relocs) / sizeof(uint32_t);
		ns->batch = gen6_null_state_batch;
		ns->items = sizeof(gen6_null_state_batch) / sizeof(uint32_t);
		return 0;
	case 7:
		ns->reloc = gen7_null_state_relocs;
		ns->nreloc = sizeof(gen7_null_state_relocs) / sizeof(uint32_t);
		ns->batch = gen7_null_state_batch;
		ns->items = sizeof(gen7_null_state_batch) / sizeof(uint32_t);
		return 0;
	default:
		return -1;
	}
}

uint32_t i915_legacy_renderstate_bytes(int gen)
{
	struct null_state ns;

	if (null_state_for(gen, &ns) != 0)
		return 0;
	return ns.items * 4;
}

int i915_legacy_renderstate_build(int gen, uint32_t *page, uint32_t page_bytes, uint32_t base)
{
	struct null_state ns;
	uint32_t i = 0, r = 0;

	if (null_state_for(gen, &ns) != 0 || ns.items * 4 > page_bytes)
		return -1;
	for (; i < ns.items; i++) {
		uint32_t s = ns.batch[i];
		if (r < ns.nreloc && i * 4 == ns.reloc[r]) {
			s += base;
			r++;
		}
		page[i] = s;
	}
	if (r != ns.nreloc)
		return -1;
	/* the rest of the cacheline, empty */
	while ((i % CACHELINE_DWORDS) && (i + 1) * 4 <= page_bytes)
		page[i++] = MI_NOOP;
	return 0;
}

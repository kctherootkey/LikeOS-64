// LikeOS -- the Gen6 and Gen7 null render state: the batch that puts the
// whole 3D pipeline into a valid, empty state.
//
// The render engine comes out of reset with its pipeline state
// undefined, and the first context image is whatever it saves of that.
// The first batch on the engine therefore sets every piece of pipeline
// state to a legal value, so that the state the engine saves -- the
// state every later context starts from -- is a working pipeline rather
// than power-on noise.
//
// The batches are the ones the vendor's tools generate for these
// generations (intel-gpu-tools' null state generator).  A few of their
// words are addresses in the batch's own page, relocated to wherever the
// batch is mapped in the global GTT (32 bits on these parts); everything
// they point at lies in the same page after the commands.
//
// Copyright (C) 2026 The LikeOS Project
// SPDX-License-Identifier for the portions derived from Intel's code: MIT
// Portions Copyright (C) 2014 Intel Corporation

